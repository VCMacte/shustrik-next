/**
 * Описание кадра — общий язык обоих способов вывода.
 *
 * Развилка «полное 3D или 2.5D» решается замером на телефоне и до него
 * открыта (docs/superpowers/specs/2026-10-21-architecture.md, «Чем развилка
 * удерживается поздней»). Открытой её держит ровно то, что здесь нет ни
 * одного слова про отрисовку: `FrameScene` — список РАЗМЕЩЕНИЙ в метрах.
 * Трёхмерный вывод развернёт их в `InstancedMesh` и узлы glTF, спрайтовый —
 * в текстурированные плоскости, и ни один из двух не станет приватной
 * правдой другого.
 */

/**
 * Имя ассета. Чем он окажется на устройстве — не наше дело.
 *
 * ДОГОВОР ОБ ИМЕНАХ. Он здесь, а не россыпью по шаблонным строкам в
 * `compose.ts`, потому что от него зависят ещё две задачи: таблица ассетов
 * (Task 4) и подсчёт бюджета по ней (Task 5). Разошлись имена — сборка
 * ломается через два этапа, и искать причину будут не здесь.
 *
 * | Имя | Чем заполняется | Откуда |
 * |---|---|---|
 * | `obstacle/<look>` | `look` препятствия: `plate`, `beam`, … | `looksFor`, `level.js:160` |
 * | `star/ring` | обычное кольцо (`worth === 1`) | `makeStars`, `view.js:2973` |
 * | `star/big` | большое кольцо (`worth > 1`) | там же |
 * | `decor/<kind>` | вид обочины: `palm`, `bush`, `rock`, … | `kindsFor`, `theme.js` |
 *
 * `look` препятствия живыми журналами не ограничен реестром `LOOKS`: в
 * сохранённых забегах встречается `beam`, которого в нынешнем реестре нет
 * (`level.js:53-57`). Описание его НЕ отвергает — повтор старого журнала
 * обязан работать, — значит и таблица ассетов Task 4 обязана его знать.
 *
 * Сегментов ДВА, и у обочины зоны в имени нет намеренно. В `run-game` 16
 * видов обочины разложены по 12 зонам, и 14 из них встречаются больше чем в
 * одной (`post` — девятью записями, `rock` — восемью) с одинаковой
 * геометрией: форму `drawDecor` выбирает по `d.kind`, а цвета берёт как
 * `THEME[d.zone]` (`view.js:891`). Значит зона — это ЦВЕТ, а не форма, и в
 * имени ассета ей места нет: `compose` разрешает её в готовый цвет и кладёт
 * в `tint` того же размещения.
 *
 * Два соглашения, без которых таблица Task 4 будет собрана неверно:
 *
 * 1. **Ассет нормирован в единицу по каждой оси.** `size` размещения — это
 *    ГАБАРИТ В МЕТРАХ (`{w, h, d}`), а не множитель к собственному размеру
 *    модели. Отсутствующее измерение значит «свой натуральный метр»; нет
 *    `size` вовсе — метровый ассет. Кто чем заполнен:
 *
 *    | Ассет | `size` |
 *    |---|---|
 *    | боковая плита | `{w: HALF − edge, h: 2.6, d: OBSTACLES.thickness}` |
 *    | верхнее полотно | `{w: corridorWidth, h: 2.6 − duckHeight, d: OBSTACLES.thickness}` |
 *    | кольцо | нет: размер у ассета свой |
 *    | обочина | `{h: k.height}`, ширина и толщина свои |
 * 2. **Начало координат ассета — в его основании** (`y` размещения — пол под
 *    ним), кроме верхнего препятствия: у него `y` — середина полотна,
 *    потому что оно висит.
 */
export type AssetId = string

/**
 * Одно размещение. Оси: `z` — метры вперёд по коридору, `x` — метры поперёк
 * (вправо положительно), `y` — метры вверх от пола. `fade` 0..1: 1 — видно
 * целиком, 0 — растворилось в дымке.
 */
export type Placement = {
  asset: AssetId
  x: number
  y: number
  z: number
  yaw?: number
  /**
   * Габарит в МЕТРАХ по каждой оси; отсутствующее измерение — своё,
   * натуральное (ассеты нормированы в единицу, см. `AssetId`).
   *
   * Трёх чисел, а не одного множителя, потому что одним боковую плиту не
   * описать: она 2.6 м высотой, полметра толщиной, а ширина у неё МЕНЯЕТСЯ
   * СО СЛОЖНОСТЬЮ (`HALF − obstacleEdge(blockFrac)`, `view.js:1236-1243`).
   * Равномерный `scale` сжал бы её по высоте вместе с шириной — то есть
   * ступень сложности меняла бы высоту препятствия.
   */
  size?: { w?: number; h?: number; d?: number }
  /**
   * ГОТОВЫЙ цвет, и никогда имя палитры. `THEME[zone]` — это не цвет, а
   * десяток ключей (`palmTrunk`, `palmLeaf`, `flower`, `rock`, …), и если
   * класть сюда имя зоны, разбирать «какой ключ у какого вида» придётся
   * КАЖДОМУ способу вывода. Две копии одной таблицы — ровно та протечка, от
   * которой заведено «одно описание, два вывода». Цвет разрешает `compose`.
   *
   * Обочина при этом красится зоной СВОЕГО элемента, а не кадра: на границе
   * зон следующая видна заранее, и в чужих цветах это выглядело бы ошибкой
   * (`view.js:887`).
   */
  tint?: string
  fade?: number
}

/** Кадр целиком. Четыре поля, и ни одного про способ вывода. */
export type FrameScene = {
  zone: string
  world: string
  /**
   * `u` — смещение тела поперёк, −1..1. `pitch` — ДОЛЯ, на которую присед
   * уводит взгляд вниз: 0 стоя, максимум при полном приседе. Доля, а не
   * градусы и не метры: чем это станет — опусканием глаз, как у старого
   * вывода, или наклоном камеры, — решает способ вывода, а описание о таком
   * не договаривается.
   */
  camera: { u: number; pitch: number }
  placements: Placement[]
}

/**
 * Дальность отсечения, метры. ЕДИНСТВЕННЫЙ владелец этого числа: по нему
 * `composeScene` выбрасывает дальнее, и его же читает бюджет кадра
 * (`estimate`). Вторая копия означала бы, что судят по одному горизонту, а
 * рисуют по другому, — тот же класс расхождения, от которого в `run-game`
 * заведены `obstacleEdge` и `obstacleDepth`.
 *
 * Совпадение с `VIEW.fogDistance` старого Canvas2D-рендерера не случайно, но
 * и не связь: там это параметр дымки в файле, который здесь переписывается,
 * а здесь — решение нового вывода, и менять его придётся по его собственным
 * причинам.
 */
export const DRAW_FAR_M = 30

/**
 * Высота стен коридора, метры. СВОЁ число нового вывода, а не заимствованное:
 * в `view.js:29` та же высота лежит как `const WALL = 2.6`, но она там не
 * экспортируется, и подсмотреть её — значит завести вторую копию молча.
 * Записана здесь с указанием источника, чтобы расхождение было видно глазом.
 * Ширину коридора брать отсюда НЕЛЬЗЯ: она своя, `VIEW.corridorWidth`.
 */
export const CORRIDOR_H_M = 2.6

/**
 * Насколько полный присед уводит взгляд вниз, в долях.
 *
 * Тоже СВОЁ число. В `run-game` `VIEW.pitchGain` значит другое — он
 * масштабирует ОПУСКАНИЕ ГЛАЗ (`view.js:125`: `y: EYE * (1 - vn *
 * VIEW.pitchGain)`), а не наклон. Значение взято равным 0.55, потому что
 * ощущение приседа у ребёнка выверено именно им, но владелец теперь здесь:
 * если новый вывод сделает из доли наклон, править придётся это число, а не
 * чужое.
 */
export const CROUCH_PITCH_GAIN = 0.55

/** Сторона коридора: −1 левая, 0 середина, 1 правая. */
export type Side = -1 | 0 | 1

/**
 * Препятствие в расписании забега (`src/core/level.js:169`). `at` — СЕКУНДА
 * забега, когда оно дойдёт до игрока, не метры: у каждого уровня своя
 * скорость, и расписание в секундах переживает её правку.
 */
export type Obstacle = {
  at: number
  kind: 'side' | 'duck'
  look: string
  side: Side
  /** Где кончается плита и начинается проём. Едет С препятствием: по нему судит `isSafe`. */
  edge: number
  passed: boolean
  hit: boolean
  verdictAt: number | null
}

/** Кольцо (`src/core/view.js:2973`). */
export type Star = {
  x: number
  z: number
  side: Side
  at: number
  taken: boolean
  worth: number
}

/** Элемент обочины (`src/core/view.js:2478`). */
export type Decor = {
  kind: string
  zone: string
  side: Side
  x: number
  y: number
  h: number
  z: number
  at: number
  phase: number
}

/**
 * Что дирижёр отдаёт на отрисовку.
 *
 * Основа — полезная нагрузка `view.render({...})` из `src/core/train.js:710`,
 * поле в поле. Сверх неё три поля, без которых `composeScene` работать не
 * может и которых в той нагрузке нет, потому что старый вид получал их при
 * создании: `world` и `step` (`train.js:104`) и `durationS` (`train.js:321`).
 *
 * Типа с таким именем в `run-game` нет — он объявлен здесь, и это НОВЫЙ код,
 * а не перевод логики на TypeScript.
 */
export type RunState = {
  decor: Decor[]
  /**
   * БОКОВАЯ скорость тела ребёнка (`train.js:710` отдаёт сюда `lastSpeed`):
   * по ней заикаются бадники. Ходом коридора она НЕ является — его задаёт
   * `tuneFor(step).speed`.
   */
  speed: number
  /** Смещение тела поперёк, −1..1. */
  u: number
  /** Присед, 0..1. */
  v: number
  /** Пройдено метров с начала забега. */
  travel: number
  stars: Star[]
  obstacles: Obstacle[]
  /** Секунд с начала забега. */
  elapsed: number
  zone: string
  prizes: Record<string, boolean>
  finishIn: number | null
  safe: boolean
  pulse: 0 | 1
  dim: number
  world: string
  /** Длина забега, секунды. */
  durationS: number
  /** Ступень сложности: по ней берётся скорость коридора. */
  step: number
}
