/**
 * Размер внутреннего буфера — ОДНО место, где он считается.
 *
 * Зачем отдельный модуль, а не две строки внутри `three/renderer.ts`: это
 * ЧЕТВЁРТОЕ число бюджета, и на него распространяется то же правило, что на
 * вызовы и вершины — **число, по которому СУДЯТ, и число, которое РИСУЮТ,
 * берутся из одного места** (CLAUDE.md). Рисует им `gl.setPixelRatio`,
 * судит по нему журнал (`bufPx` в окне здоровья), и обе дороги обязаны
 * выходить из одной функции. Своя арифметика в журнале означала бы бюджет,
 * который уверенно врёт — ровно то, от чего правило поставлено.
 *
 * И поэтому же модуль НЕ импортирует `three`: функция обязана считаться в
 * `node`, в прогоне, без телефона и без GL-контекста.
 *
 * Чего здесь нет: выбора стиля. `small` — это не «пиксельная графика», а
 * ровно один замер (см. `BufferPolicy`). Арт, атласы и фильтрация к этому
 * файлу отношения не имеют.
 */

/**
 * Что делать с внутренним разрешением.
 *
 * `full` — как рисовалось до сих пор: доля от плотности экрана.
 *
 * `small` — АБСОЛЮТНЫЙ потолок по числу пикселей, картинка растягивается на
 * экран ближайшим соседом (растяжение делает страница, см. `spike.html`,
 * класс `pixel`). Это та самая вторая возможность, которая записана в
 * комментарии к `RENDER_SCALE` с самого начала: «либо замер подтвердит долю,
 * либо на её место встанет абсолютный потолок по числу пикселей буфера, как
 * у старого вывода».
 *
 * ЗАЧЕМ ЭТО МЕРИТЬ. Спайк 21 октября оставил одну неизвестность, и она
 * решает формат проекта: чем картинка облагает ПРОЦЕССОРНЫЙ инференс —
 * работой CPU или полосой памяти (спека, «Неизвестность, которая решает
 * формат»). Данные намекали на полосу: подводный мир облагал сильнее (109 мс
 * против 94) при МЕНЬШЕМ числе заливок. Малый буфер режет площадь ПРОХОДА
 * ОТРИСОВКИ — чтения и записи цвета и глубины плюс работу шейдеров — в
 * ШЕСТЬ С ПОЛОВИНОЙ РАЗ на телефоне спайка (посчитано ниже, у
 * `SMALL_BUFFER_W`), не меняя ни вызовов, ни вершин, ни одного ассета.
 *
 * Две оговорки сказаны прямо, чтобы потом не удивляться половинчатому
 * эффекту. Первая: «в шестнадцать раз», как сначала было написано здесь, —
 * неправда. Шестнадцать получается только если считать от 1920×1080, а
 * полный буфер и сам не равен экрану: `min(dpr, 2) × 0.7` на этом телефоне
 * даёт 1222×550, а не 1080 в ширину. Вторая: полный экран композитор
 * браузера пишет по-прежнему, и эта часть трафика не уходит никуда — шесть с
 * половиной раз относятся к проходу вывода, а не ко всей памяти кадра.
 *
 * Шести раз для ответа хватает с большим запасом: разброс устройства — ±8
 * fps, а прогон двигает ровно полосу и ничего больше. Поэтому ответ читается
 * прямо: инференс на процессоре упал к 87 мс — дело в полосе, остался на
 * 109 — дело в работе CPU.
 */
export type BufferPolicy = 'full' | 'small'

/**
 * Доля от плотности экрана у `full`.
 *
 * ЧИСЛО ВЫБРАНО НАМИ И НИЧЕМ ПОКА НЕ ОБОСНОВАНО, кроме здравого смысла.
 * Говорится это прямо, потому что ранняя версия комментария выводила 0.7 из
 * старого вывода, и вывод был натянут: `VIEW.width`/`VIEW.height` фиксируют
 * буфер 1280×720 и игнорируют DPR вовсе («Miracast всё равно пережимает в
 * 720p, рисовать выше — чистый нагрев на GPU, который уже делят
 * распознавание и кодировщик», `src/core/config.js:377`), а
 * `min(dpr, 2) × 0.7` никакого потолка в 720p НЕ ставит: на плотном экране
 * буфер уедет выше. Это не «та же мысль, выраженная долей» — это другая
 * мысль, и притворяться иначе нельзя.
 *
 * В спеке этого числа тоже нет: план и бриф этапа говорят «0.7 из спеки», но
 * в тексте `docs/superpowers/specs/2026-10-21-architecture.md` его нет ни
 * разу — проверено поиском.
 *
 * Чем оно станет: ЗАМЕРОМ, и `small` рядом — первый шаг этого замера. До
 * ответа менять долю по вкусу нельзя: ровно так потолки и уползают.
 */
export const RENDER_SCALE = 0.7

/**
 * Потолок плотности экрана. Выше двух множить незачем: 0.7 от тройной
 * плотности — это втрое больше пикселей ради картинки, которую Miracast
 * всё равно пережмёт в 720p.
 */
export const MAX_DPR = 2

/**
 * Потолок малого буфера, пиксели. 16:9 — то же отношение, что у `VIEW`.
 *
 * Что из этого выходит на телефоне спайка (Redmi Note 11 Pro 5G, 1080×2400,
 * `dpr` 2.75, горизонтально — CSS-окно примерно 873×393):
 *
 *   полный буфер   1222×550  ≈ 672 000 пикселей
 *   малый буфер     480×216  ≈ 104 000 пикселей   — в 6.5 раза меньше
 *
 * Малый выходит 480×216, а НЕ 480×270: окно шире 16:9 (2.22:1), и потолок
 * связывает ширина. Ровно затем в `bufferFor` и стоит минимум по обеим осям
 * — потолок по одной растянул бы картинку.
 *
 * ЧЕМ ВЫБРАНО 480. Не «поменьше на глаз» и не ради самого большого эффекта:
 * прогон обязан мерить разрешение, которое мы готовы ВЫПУСТИТЬ. Возьми 320×180
 * — замер вышел бы чище (13 раз вместо 6.5), но ответ был бы про картинку,
 * на которую никто не соглашался, и бюджет записал бы кадр, которого не
 * будет. 480 в ширину — это 2.7 пикселя потока Miracast (1280 в ширину) на
 * один арт-пиксель: кодек режет цветность сильнее светлоты и съедает резкие
 * границы звоном, и 2.7 — та граница, за которой пиксель ещё доживает до
 * телевизора крупной формой. Покажет выезд звон — следующий шаг 320×180, но
 * он СЛЕДУЮЩИЙ, а не вместо.
 *
 * ЭТО МОЙ ВЫБОР, А НЕ ЗАМЕР. Записано здесь по правилу «потолки записаны
 * ЗАРАНЕЕ» (CLAUDE.md), и менять его задним числом под полученное число —
 * ровно то, от чего эта запись защищает.
 */
export const SMALL_BUFFER_W = 480
export const SMALL_BUFFER_H = 270

/** Буфер кадра: множитель для вывода и пиксели для журнала. */
export type BufferSize = {
  /** Множитель к размеру холста — то, что уходит в `setPixelRatio`. */
  ratio: number
  w: number
  h: number
  /** Пикселей в кадре. ЧЕТВЁРТОЕ число бюджета, которого `estimate` не знает. */
  px: number
}

/**
 * Какой буфер рисовать на холсте `w × h` при плотности `dpr`.
 *
 * `small` — ПОТОЛОК, а не множитель: берётся минимум с полной долей, и на
 * мелком экране малый прогон не окажется ВЫШЕ полного. Без этого минимума
 * пара прогонов на планшете с низкой плотностью сравнивала бы малый буфер с
 * ещё меньшим полным, и знак эффекта в таблице перевернулся бы.
 */
export function bufferFor(
  policy: BufferPolicy,
  w: number,
  h: number,
  dpr: number,
): BufferSize {
  const full = Math.min(dpr, MAX_DPR) * RENDER_SCALE
  const ratio =
    policy === 'small' ? Math.min(full, SMALL_BUFFER_W / w, SMALL_BUFFER_H / h) : full
  /* ВНИЗ, и тем же выражением, каким считает three.js: `WebGLRenderer.setSize`
     делает ровно `Math.floor(width * pixelRatio)`. Здесь сначала стояло
     округление к ближайшему, и расхождение нашлось НЕ рассуждением, а
     запуском страницы: на окне 929×823 журнал записал буфер 305×270, а в
     контексте оказалось 304×270. Один пиксель — но это ровно тот разлад, от
     которого поставлен весь инвариант: число, по которому судят, перестало
     быть числом, которое рисуют.
     Цена точного совпадения — некруглые числа там, где ждёшь круглых:
     720 × 1.4 в двоичной дроби равно 1007.9999999999999, и буфер выходит
     1792×1007. Так и надо: 1008 было бы красивее и неверно. */
  const bw = Math.floor(w * ratio)
  const bh = Math.floor(h * ratio)
  return { ratio, w: bw, h: bh, px: bw * bh }
}
