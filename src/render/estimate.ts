/**
 * Бюджет кадра — по ОПИСАНИЮ сцены, в `node`, без телефона и без GPU.
 *
 * Правило, ради которого этот файл отдельный: **число, по которому СУДЯТ, и
 * число, которое РИСУЮТ, берутся из одного места** (CLAUDE.md; спека,
 * «Бюджет считается по описанию, а не по устройству»). На устройстве
 * `renderer.stats()` отдаст живые вызовы и вершины, и тест сверит их с
 * `estimate` ТОГО ЖЕ кадра. Поэтому здесь нет ни одной прикидки «на глаз»:
 * всё, что складывается, приходит из `assets/manifest.json`, который считан
 * из настоящих контейнеров glTF (`tools/asset-stat.mjs`).
 *
 * Импорт `three` сюда закрыт сторожем `tests/guards.test.ts`, и это смысл
 * файла, а не помеха ему: бюджет обязан считаться там, где `three` нет
 * вовсе, — иначе он перестанет быть проверкой РАЗВИЛКИ «3D или 2.5D» и
 * станет проверкой одной её половины.
 *
 * Чего эти числа НЕ значат: сложность ассетов в таблице НАЗНАЧЕНА автором
 * заглушек, а не замерена (`docs/art-placeholders.md`). Правдива МЕХАНИКА
 * СЧЁТА; предсказанием кадров в секунду она не становится.
 */
import type { AssetId, FrameScene, Placement } from './types'

/** Цена одного ассета — строка `assets/manifest.json`, поле в поле. */
export type AssetCost = {
  /** Вызовов отрисовки на ассет: по числу ПРИМИТИВОВ, а не мешей. */
  calls: number
  /** Вершин на одно размещение (`accessors[POSITION].count`). */
  verts: number
  /** Байт текстур ассета, резидентно — один раз, сколько бы его ни стояло. */
  texBytes: number
}

/** Таблица ассетов целиком: имя → цена. */
export type AssetTable = Record<AssetId, AssetCost>

/** Три числа, которыми судится кадр. */
export type Budget = {
  calls: number
  verts: number
  texBytes: number
}

/*
 * ПОТОЛКИ. Записаны ЗАРАНЕЕ, до замера, и задним числом не правятся —
 * правило `run-game`, перенесённое в CLAUDE.md и в спеку («Бюджеты,
 * записанные ЗАРАНЕЕ»). Здесь они объявлены ОДИН раз, потому что иначе
 * сравнений с потолком станет столько же, сколько у них читателей, и
 * поднять потолок можно будет молча в одном из них. Тест сверяет эти
 * значения с текстом спеки — то есть подъём числа здесь обязан быть
 * подъёмом числа в спеке, и наоборот.
 */

/** Вызовов отрисовки в кадре — жёсткий потолок. */
export const CEILING_CALLS = 150
/** Мягкий рубеж вызовов: за ним добавлять украшения без замера нельзя. */
export const SOFT_CALLS = 100
/** Вершин в кадре. */
export const CEILING_VERTS = 100_000
/** Текстурная память кадра, байты (96 МБ). */
export const CEILING_TEX_BYTES = 96 * 1024 * 1024

/**
 * Цена ассета или ГРОМКИЙ отказ.
 *
 * Молчаливый `?? 0` здесь был бы худшим из возможных решений: имена ассетов
 * — договор трёх задач сразу (`types.ts`, «ДОГОВОР ОБ ИМЕНАХ»), и ассет, у
 * которого нет строки в таблице, означает либо разъехавшиеся имена, либо
 * ассет, который на устройстве станет БЕЛОЙ заглушкой. И то и другое должно
 * падать на счёте, а не выясняться на телевизоре. Сложение же без отказа
 * дало бы `NaN`, а `NaN < 150` — ложь, то есть бюджет начал бы «не
 * укладываться» без всякого объяснения.
 */
function costOf(id: AssetId, assets: AssetTable): AssetCost {
  const cost = assets[id]
  if (!cost) throw new Error(`ассета ${id} нет в таблице`)
  return cost
}

/**
 * Что стоит в кадре ВСЕГДА, сверх размещений.
 *
 * `composeScene` выдаёт только `obstacle/*`, `star/*` и `decor/*` — и это
 * правильно: пол, стены и небо не РАЗМЕЩАЮТСЯ, они есть всегда и ровно по
 * одному. Но рисуются они каждый кадр и стоят вызовов, вершин и текстур,
 * поэтому бюджет, который считает только размещения, занижает ровно на эту
 * постоянную часть. Правило «судят и рисуют по одному числу» такого не
 * прощает: вывод нарисует коридор и небо, а счётчик о них не узнает.
 *
 * Небо берётся по ЗОНЕ кадра, а не одно на игру: небес двенадцать, по одному
 * на зону, и все двенадцать разом — это 32 МБ из 75 (`art-placeholders.md`).
 * В кадре нужна одна зона, и бюджет кадра обязан считать именно её.
 *
 * Возвращается СПИСОК ИМЁН, а не готовые числа: так постоянная часть
 * проходит ровно через тот же `costOf`, что и размещения, — включая громкий
 * отказ на незнакомом имени, — и остаётся видимой глазом в выводе прогона.
 */
export function backdropAssets(scene: Pick<FrameScene, 'zone'>): AssetId[] {
  return ['corridor/floor', 'corridor/walls', `sky/${scene.zone}`]
}

/**
 * Считает список размещений. `instanced` — главное правило счёта.
 *
 * ИНСТАНСИРОВАНИЕ. Размещения с ОДНИМ именем ассета сливаются в одну
 * отрисовку (`InstancedMesh` трёхмерного вывода, один батч спрайтов у
 * двумерного), поэтому вызовы считаются по РАЗНЫМ ассетам. Вершины — по
 * ВСЕМ размещениям: слияние в один вызов не делает вторую пальму бесплатной
 * для вершинного конвейера. Текстуры — тоже по разным ассетам: карта
 * резидентна один раз.
 *
 * `instanced = false` — не отладочный ключ, а второе ЧИСЛО, которое прогон
 * обязан печатать рядом. Запас, который даёт инстансирование, не замерен, и
 * пока он не назван двумя числами, «укладываемся» держится на честном
 * слове: вывод, который забудет инстансировать, уложится или нет — вопрос
 * не договорённости, а счёта.
 */
function sum(placements: Placement[], assets: AssetTable, instanced: boolean): Budget {
  let calls = 0
  let verts = 0
  let texBytes = 0
  const counted = new Set<AssetId>()

  for (const p of placements) {
    const cost = costOf(p.asset, assets)
    /* Вершины — всегда по размещению: вторая пальма даёт столько же вершин,
       в один вызов она попала или в свой. */
    verts += cost.verts

    const firstOfItsKind = !counted.has(p.asset)
    if (firstOfItsKind) counted.add(p.asset)

    /* Текстура резидентна в видеопамяти ОДИН раз, сколько бы раз её ни
       нарисовали, — и это не зависит от инстансирования. Поэтому `texBytes`
       считается по разным ассетам в ОБЕИХ ветках. Первая версия умножала её
       на размещения в ветке без инстансирования: число никуда не судилось,
       но оно отдаётся наружу, и заряженная цифра в открытом API рано или
       поздно будет кем-то прочитана как правда. */
    if (firstOfItsKind) texBytes += cost.texBytes

    /* А вот ВЫЗОВЫ без инстансирования — по каждому размещению: именно в
       этом разница между «слили в один батч» и «нарисовали по одному». */
    if (!instanced || firstOfItsKind) calls += cost.calls
  }

  return { calls, verts, texBytes }
}

/**
 * Бюджет ТОГО ОПИСАНИЯ, которое дали, с инстансированием.
 *
 * Постоянную часть кадра (коридор и небо) сам НЕ добавляет — её вносит
 * `estimateFrame`. Разделение не косметическое: `estimate` обязан быть
 * чистой суммой по списку размещений, иначе пустой список перестанет давать
 * нули и сверять живой `renderer.stats()` с ним станет нечем. Судить КАДР
 * надо `estimateFrame`; `estimate` сам по себе — счёт размещений, и
 * занижает он ровно на постоянную часть.
 */
export function estimate(scene: FrameScene, assets: AssetTable): Budget {
  return sum(scene.placements, assets, true)
}

/** То же, но каждое размещение — своя отрисовка. Второе число прогона. */
export function estimateWithoutInstancing(scene: FrameScene, assets: AssetTable): Budget {
  return sum(scene.placements, assets, false)
}

/**
 * Бюджет КАДРА целиком: размещения плюс постоянная часть.
 *
 * Отдаёт и слагаемые, а не только сумму: постоянная часть обязана быть
 * видимой отдельной строкой — иначе она растворится в сумме и однажды
 * исчезнет из счёта так, что этого никто не заметит. Там же и число без
 * инстансирования, рядом, в одном объекте: два числа, напечатанные вместе,
 * — единственный способ не выдать запас за измеренный.
 */
export type FrameBudget = Budget & {
  /** Вызовы, если вывод НЕ инстансирует (постоянная часть тоже внутри). */
  callsNoInstancing: number
  /** Коридор и небо: то, что стоит в кадре всегда. */
  backdrop: Budget
  /** Только размещения, с инстансированием. */
  placements: Budget
}

export function estimateFrame(scene: FrameScene, assets: AssetTable): FrameBudget {
  /*
   * ПОСТОЯННАЯ ЧАСТЬ НЕ ДОЛЖНА ДВОИТЬСЯ С РАЗМЕЩЕНИЯМИ, и держаться это
   * обязано проверкой, а не комментарием.
   *
   * Сегодня `composeScene` выдаёт только `obstacle/*`, `star/*` и `decor/*`,
   * поэтому прямое сложение ниже ничего не двоит. Но это свойство ЧУЖОГО
   * файла, а не наше: начни `compose` однажды выдавать `sky/*` — скажем,
   * чтобы спрайтовый вывод разместил небо сам, — и небо посчиталось бы
   * дважды, молча и в ту сторону, которая делает бюджет ТЯЖЕЛЕЕ правды, то
   * есть без всякого внешнего признака. Отказ здесь громкий и немедленный:
   * если постоянная часть переехала в описание, слагаемое ниже обязано
   * уехать вместе с ней, а не остаться вторым.
   */
  const standing = new Set(backdropAssets(scene))
  for (const p of scene.placements) {
    if (standing.has(p.asset)) {
      throw new Error(
        `размещение ${p.asset} уже посчитано как постоянная часть кадра:` +
          ' оно удвоилось бы в бюджете',
      )
    }
  }

  const placements = estimate(scene, assets)
  /* Постоянная часть идёт через тот же счётчик, что и размещения: иначе у
     неё завелась бы своя арифметика, и расходиться они начали бы молча.
     Инстансирование ей безразлично — каждый из трёх ассетов в кадре один. */
  const backdropPlacements: Placement[] = backdropAssets(scene).map((asset) => ({
    asset,
    x: 0,
    y: 0,
    z: 0,
  }))
  const backdrop = sum(backdropPlacements, assets, true)
  const noInst = sum([...backdropPlacements, ...scene.placements], assets, false)

  /* Текстуры складываются по РАЗНЫМ ассетам, и коридор с небом в размещениях
     не встречаются (`composeScene` таких имён не выдаёт), поэтому прямое
     сложение здесь не двоит ни одной карты. */
  return {
    calls: placements.calls + backdrop.calls,
    verts: placements.verts + backdrop.verts,
    texBytes: placements.texBytes + backdrop.texBytes,
    callsNoInstancing: noInst.calls,
    backdrop,
    placements,
  }
}
