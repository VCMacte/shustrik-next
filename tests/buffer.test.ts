/**
 * Внутреннее разрешение: одно место, где оно считается.
 *
 * Зачем отдельный файл проверок на двадцать строк кода. Это ЧЕТВЁРТОЕ число
 * бюджета, и у него та же обязанность, что у вызовов и вершин: число, по
 * которому СУДЯТ, и число, которое РИСУЮТ, берутся из одного места
 * (CLAUDE.md). Рисует им `setPixelRatio`, судит по нему журнал спайка
 * (`bufPx`), и если они разойдутся, замер будет уверенно врать — а на этом
 * числе стоит ответ на единственный оставшийся вопрос спайка: чем картинка
 * облагает процессорный инференс, полосой памяти или работой CPU.
 *
 * Все ожидания здесь — ЛИТЕРАЛАМИ, ни одного через `bufferFor` или через
 * `SMALL_BUFFER_*`. Иначе проверка сверяла бы функцию саму с собой: потолок,
 * уехавший до 960×540, оставил бы её зелёной, а именно сползание потолка эти
 * записи и обязаны ловить.
 */
import { expect, test } from 'vitest'

import { MAX_DPR, RENDER_SCALE, bufferFor } from '../src/render/buffer'

/**
 * Телефон спайка: Redmi Note 11 Pro 5G, 1080×2400, `dpr` 2.75,
 * горизонтально — CSS-окно примерно 873×393 (спека, «Устройство»).
 */
const PHONE = { w: 873, h: 393, dpr: 2.75 }

test('полный буфер — доля 0.7 от плотности экрана с потолком 2', () => {
  const full = bufferFor('full', PHONE.w, PHONE.h, PHONE.dpr)
  // 2.75 зажато потолком до 2, дальше 2 × 0.7 = 1.4.
  expect(full.ratio).toBeCloseTo(1.4, 6)
  expect([full.w, full.h]).toEqual([1222, 550])
  expect(full.px).toBe(1222 * 550)

  /* Потолок плотности проверяется отдельным замером, а не чтением
     константы: без зажима тройная плотность дала бы 2.1, и буфер уехал бы
     вверх ровно на том телефоне, где кадров и так не хватает. */
  expect(bufferFor('full', PHONE.w, PHONE.h, 3).ratio).toBeCloseTo(1.4, 6)
  expect(bufferFor('full', PHONE.w, PHONE.h, 1).ratio).toBeCloseTo(0.7, 6)
  expect(RENDER_SCALE).toBe(0.7)
  expect(MAX_DPR).toBe(2)
})

/**
 * Малый буфер на телефоне спайка — 480×216, и связывает его ШИРИНА.
 *
 * Прошла бы вхолостую? НЕТ, и ошибка была найдена этим счётом, а не
 * рассуждением: окно телефона горизонтально имеет отношение 2.22:1, то есть
 * шире 16:9, и «480×270» в голове автора не равно тому, что окажется в
 * буфере. Проверь здесь только площадь — ошибка в выборе оси (минимум по
 * высоте вместо минимума по обеим) осталась бы зелёной, а картинка на
 * телефоне оказалась бы растянутой.
 */
test('малый буфер связан узкой осью и равен 480×216 на телефоне спайка', () => {
  const small = bufferFor('small', PHONE.w, PHONE.h, PHONE.dpr)
  expect([small.w, small.h]).toEqual([480, 216])
  expect(small.px).toBe(480 * 216)

  /* Во столько раз прогон облегчает проход отрисовки. Число записано
     ЗАРАНЕЕ (`src/render/buffer.ts`, `SMALL_BUFFER_W`) и под полученный
     замер не меняется: при шести с половиной разах эффект обязан быть видно
     поверх разброса устройства ±8 fps, и если здесь однажды окажется 1.5 —
     значит мерить уже нечего. */
  const full = bufferFor('full', PHONE.w, PHONE.h, PHONE.dpr)
  expect(full.px / small.px).toBeCloseTo(6.48, 2)
})

/**
 * Малый буфер — ПОТОЛОК, а не множитель.
 *
 * Прошла бы вхолостую? НЕТ: убери минимум с полной долей, и на экране
 * меньше 480 точек малый прогон окажется ВЫШЕ полного. Пара прогонов
 * сравнивала бы тогда малый буфер с ещё меньшим полным, и знак эффекта в
 * таблице перевернулся бы — то есть замер дал бы ответ, противоположный
 * правде, и выглядел бы при этом правдоподобно.
 */
test('малый буфер никогда не выше полного', () => {
  // Узкое окно с низкой плотностью: полная доля здесь и так меньше потолка.
  const small = bufferFor('small', 320, 180, 1)
  const full = bufferFor('full', 320, 180, 1)
  expect(small.ratio).toBeCloseTo(0.7, 6)
  expect(small.px).toBe(full.px)
  expect(small.px).toBeLessThanOrEqual(full.px)
})

/**
 * Стороны округляются ВНИЗ — тем же выражением, каким считает three.js.
 *
 * Прошла бы вхолостую? НЕТ, и расхождение найдено не рассуждением, а
 * запуском страницы: округление к ближайшему записало в журнал буфер
 * 305×270 при настоящем 304×270. Один пиксель, но разлад тот самый — число,
 * по которому СУДЯТ, перестало быть числом, которое РИСУЮТ.
 *
 * Поэтому здесь взято окно, на котором две формулы дают РАЗНОЕ: 823 × 0.7 =
 * 576.1 вниз даёт 576, а 929 × 0.328… = 304.7 вниз даёт 304 против 305 к
 * ближайшему. Верни `Math.round` — и падает ровно эта строка.
 */
test('стороны буфера округляются вниз, как в setSize', () => {
  const b = bufferFor('small', 929, 823, 1)
  expect([b.w, b.h]).toEqual([304, 270])
  expect(b.px).toBe(b.w * b.h)

  /* И тот случай, где вниз даёт некруглое: 720 × 1.4 в двоичной дроби —
     1007.99…, значит 1007, а не 1008. Красивее было бы неверно. */
  expect(bufferFor('full', 1280, 720, 2).h).toBe(1007)
})

/**
 * Холст нулевого размера.
 *
 * Это не выдуманный случай: страница спайка запускает прогон, показав экран
 * прогона, и ровно эта ошибка там уже оплачена — «канва на скрытом экране
 * имеет нулевой размер, и буфер отрисовки завёлся бы нулевым»
 * (`spike.ts`, `makePult`). Ноль пикселей обязан остаться нулём и попасть в
 * журнал нулём: это честное «рисовать было некуда», а не `NaN` и не
 * единица, которую потом примут за кадр.
 */
test('нулевой холст даёт нулевой буфер, а не NaN', () => {
  const b = bufferFor('small', 0, 0, 2)
  expect(b.px).toBe(0)
  expect(Number.isNaN(b.px)).toBe(false)
})
